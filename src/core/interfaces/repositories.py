from typing import Protocol, Optional
from src.core.entities.post import Post
from src.core.entities.tag import Tag
from src.core.entities.user import User
from src.core.entities.comment import Comment

class UserRepositoryProtocol(Protocol):
    def get_by_id(self, user_id: int) -> User | None: ...
    def get_by_username(self, username: str) -> User | None: ...
    def get_by_email(self, email: str) -> User | None: ...
    def create(self, user: User) -> User: ...
    def update(self, user: User) -> User: ...
    def soft_delete(self, user_id: int) -> None: ...

class PostRepositoryProtocol(Protocol):
    def get_by_id(self, post_id: int) -> Optional[Post]: ...
    def get_by_slug(self, slug: str) -> Optional[Post]: ...
    def list_posts(self, skip: int, limit: int, published_only: bool,
                   author_id: int | None = None,
                   keyword: str | None = None) -> list[Post]: ...
    def create(self, post: Post) -> Post: ...
    def update(self, post: Post) -> Post: ...
    def soft_delete(self, post_id: int) -> None: ...

class TagRepositoryProtocol(Protocol):
    def get_by_name(self, name: str) -> Optional[Tag]: ...
    def list_all(self) -> list[Tag]: ...
    def get_or_create(self, name: str) -> Tag: ...


class CommentRepositoryProtocol(Protocol):
    def get_by_id(self, comment_id: int) -> Optional[Comment]: ...
    def list_by_post(self, post_id: int, skip: int, limit: int) -> list[Comment]: ...
    def create(self, comment: Comment) -> Comment: ...
    def soft_delete(self, comment_id: int) -> None: ...